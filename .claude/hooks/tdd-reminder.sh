    "hookEventName": "PreToolUse",
    "additionalContext": "[TDD 리마인더 - .claude/rules/tdd.md는 Rigid 규칙이다]\n이 파일이 비즈니스 로직, API, 유틸/순수 함수, 버그 수정에 해당하면 TDD 필수다. 타입 정의, 설정 파일, 로직 없는 순수 UI는 제외다. UI 안에 분기/상태 로직이 있으면 로직을 분리해 TDD를 적용한다.\n1) RED: 동작 하나당 테스트 하나를 먼저 쓰고 반드시 실행해 실패를 눈으로 확인한다. 실패 이유는 기능 미구현이어야 하며 문법/import 오류는 RED가 아니다. 버그 수정은 버그를 재현하는 실패 테스트가 먼저다.\n2) GREEN: 테스트를 통과시키는 최소한의 코드만 쓴다(YAGNI). 신규/기존 테스트를 모두 실행해 통과를 확인한다.\n3) REFACTOR: 중복 제거, 이름 개선만 한다. 새 동작은 다음 RED에서 추가한다.\n지금 수정하려는 프로덕션 코드에 대응하는 실패 테스트를 이미 실행해 확인했는가? 아니라면 이 편집을 멈추고 테스트부터 작성하라. 테스트보다 프로덕션 코드를 먼저 썼다면 그 코드를 삭제하고 RED부터 다시 시작한다(참고용 보관, 주석 처리 포함 금지). '단순해서', '나중에', '시간이 없어서', '프로토타입이라서'는 변명이다."
